/*
 * vws_emit.c -- turn a VwsForm into a runnable .wet Lua script.
 *
 * The output is a plain .WET applet, so the designer's save is also the
 * runnable file.  Handler bodies are emitted verbatim from what the loader
 * captured, which is what makes a re-emit safe: user code is never regenerated.
 */
#include "vws_internal.h"

#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* ----------------------------------------------------------- string escape */

/* Emit a Lua double-quoted literal. */
static void emit_lua_string(char **out, size_t *cap, size_t *len, const char *s) {
    static const char hex[] = "0123456789abcdef";
    #define PUSH(ch) do { \
        if (*len + 1 >= *cap) { *cap = *cap ? *cap * 2 : 256; \
            *out = (char *)realloc(*out, *cap); } \
        (*out)[(*len)++] = (ch); \
    } while (0)

    PUSH('"');
    for (const unsigned char *p = (const unsigned char *)(s ? s : ""); *p; p++) {
        switch (*p) {
        case '"':  PUSH('\\'); PUSH('"');  break;
        case '\\': PUSH('\\'); PUSH('\\'); break;
        case '\n': PUSH('\\'); PUSH('n');  break;
        case '\r': PUSH('\\'); PUSH('r');  break;
        case '\t': PUSH('\\'); PUSH('t');  break;
        default:
            if (*p < 0x20) {
                PUSH('\\'); PUSH('x');
                PUSH(hex[*p >> 4]); PUSH(hex[*p & 0xF]);
            } else {
                PUSH((char)*p);
            }
        }
    }
    PUSH('"');
    #undef PUSH
}

static void emit_line(char **out, size_t *cap, size_t *len, const char *fmt, ...) {
    char buf[1024];
    va_list ap;
    va_start(ap, fmt);
    int n = vsnprintf(buf, sizeof buf, fmt, ap);
    va_end(ap);
    if (n < 0) return;
    if ((size_t)n >= sizeof buf) n = sizeof buf - 1;
    if (*len + (size_t)n + 1 >= *cap) {
        *cap = (*cap ? *cap : 256) + (size_t)n + 256;
        *out = (char *)realloc(*out, *cap);
    }
    memcpy(*out + *len, buf, (size_t)n);
    *len += (size_t)n;
}

/* ---------------------------------------------------------------- emitter */

void vws_emit_applet(const VwsForm *f, VwsSource *handlers, char **out) {
    if (!f || !out) return;

    size_t cap = 1024, len = 0;
    char *buf = (char *)malloc(cap);
    if (!buf) return;

    emit_line(&buf, &cap, &len,
              "-- %s.vws -- Visual WuBu System\n"
              "-- Generated by the designer.  Edit here or in VWS; handler\n"
              "-- bodies below are preserved verbatim across re-emits.\n\n",
              f->title);

    /* User handlers first, exactly as they were written. */
    for (int i = 0; i < f->nhandlers; i++) {
        emit_line(&buf, &cap, &len, "function %s(self)\n%s\nend\n\n",
                  f->handlers[i].name, f->handlers[i].body ? f->handlers[i].body : "");
    }
    (void)handlers;

    /* The applet.  Absolute positions -> wet.canvas, which is VB's model. */
    emit_line(&buf, &cap, &len, "wet.applet {\n");
    emit_line(&buf, &cap, &len, "  title = ");
    emit_lua_string(&buf, &cap, &len, f->title);
    emit_line(&buf, &cap, &len, ",\n");
    emit_line(&buf, &cap, &len, "  width = %d, height = %d,\n", f->width, f->height);
    emit_line(&buf, &cap, &len, "  content = wet.canvas {\n");
    if (f->count == 0) {
        emit_line(&buf, &cap, &len, "    children = {},\n");
    } else {
        emit_line(&buf, &cap, &len, "    children = {\n");
        for (VwsControl *c = f->controls; c; c = c->next) {
            emit_line(&buf, &cap, &len, "      wet.%s { id=", c->cls);
            emit_lua_string(&buf, &cap, &len, c->id);
            emit_line(&buf, &cap, &len, ", left=%d, top=%d, w=%d, h=%d",
                      c->left, c->top, c->w, c->h);
            if (c->text[0]) {
                emit_line(&buf, &cap, &len, ", text=");
                emit_lua_string(&buf, &cap, &len, c->text);
            }
            if (c->handler[0]) {
                emit_line(&buf, &cap, &len, ", onclick=%s", c->handler);
            }
            emit_line(&buf, &cap, &len, " },\n");
        }
        emit_line(&buf, &cap, &len, "    },\n");
    }
    emit_line(&buf, &cap, &len, "  }\n");
    emit_line(&buf, &cap, &len, "}\n");

    /* Terminate. */
    if (len + 1 > cap) { cap = len + 1; buf = (char *)realloc(buf, cap); }
    buf[len] = '\0';
    *out = buf;
}

char *vws_form_emit(const VwsForm *f) {
    char *out = NULL;
    vws_emit_applet(f, NULL, &out);
    return out;
}
